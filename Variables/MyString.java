public class MyString{
	public static void main(String[] args){
		String name = "Faryal Sarfraz";
		int age = 18;
		String blank = " ";
		String text1 = "My name is";
		String text2 = "I am";
		String text3 = "years old";
		String stop = ".";

		System.out.println(text1 + blank + name + stop);
		System.out.println(text2 + blank + age + blank + text3 + stop);

		System.out.println("My name is Faryal Sarfraz.");
		System.out.println("I am 18 years old.");
	}
}